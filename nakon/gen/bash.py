"""Generate the Linux side of a plan: run.sh, step scripts, and vars files.

Step bodies stay in separate files (never inlined into run.sh): inlining breaks
on `exit`/`set -e`/heredoc delimiters in catalog scripts, and separate files
give each step its own process, exit code, and working directory.
"""

import shlex

from . import _WHITESPACE, MARKER_BEGIN, MARKER_DONE, MARKER_RC, step_basename, step_label

# Generous: large installers take a while. Override with NAKON_STEP_TIMEOUT.
DEFAULT_STEP_TIMEOUT = 1800

_INTERPRETER = {"bash": "bash", "command": "sh"}


def render_vars(var_values: dict) -> str:
    """Shell-quoted assignments, sourced under `set -a` in the step's subshell."""
    lines = [f"{key}={shlex.quote(str(value))}" for key, value in sorted(var_values.items())]
    return "".join(f"{line}\n" for line in lines)


def _preamble(plan_id: str, bundle_id: str, total: int, version: str) -> str:
    return f"""#!/usr/bin/env bash
# GENERATED BY nakon {version} — do not edit.
#   bundle {bundle_id}
#   plan   {plan_id}
#   {total} step(s), platform=linux
#
# No `set -e`: one failing step must not abort the rest.
#
# Drop stdin first: a password line fed for `sudo -S` would otherwise leak to a child
# under a NOPASSWD rule.
exec </dev/null

PLAN_DIR="$(cd -- "$(dirname -- "${{BASH_SOURCE[0]}}")" && pwd)"
REPORT="$PLAN_DIR/report.tsv"
TOTAL={total}
STEP_TIMEOUT="${{NAKON_STEP_TIMEOUT:-{DEFAULT_STEP_TIMEOUT}}}"
FAILED=0
: > "$REPORT"

nakon_record() {{  # idx name kind rc secs
    printf '%s\\t%s\\t%s\\t%s\\t%s\\n' "$1" "$2" "$3" "$4" "$5" >> "$REPORT"
    printf '%s %s\\t%s\\t%s\\n' "{MARKER_RC}" "$1" "$4" "$5"
    [ "$4" -eq 0 ] || FAILED=$((FAILED + 1))
}}

# One step as root: its own CWD, vars, and exit code.
nakon_step_root() {{  # script workdir varsfile interp
    (
        cd -- "$2" || exit 127
        # `set -a` exports vars into the step's own process.
        if [ -n "$3" ]; then set -a; . "$3"; set +a; fi
        exec timeout -k 30 "$STEP_TIMEOUT" "$4" "$1"
    )
}}

# One step as run_as. The plan dir is unreadable to that account, so stage a copy.
nakon_step_user() {{  # script workdir varsfile interp user
    local stage rc
    stage="$(mktemp -d /tmp/nakon-runas.XXXXXXXX)" || return 127
    chmod 0700 "$stage" || {{ rm -rf "$stage"; return 127; }}
    if [ -n "$2" ] && [ -d "$2" ]; then cp -a "$2/." "$stage/" 2>/dev/null || true; fi
    cp -a "$1" "$stage/step" || {{ rm -rf "$stage"; return 127; }}
    if [ -n "$3" ]; then cp -a "$3" "$stage/vars.env" || true; fi
    if ! chown -R "$5" "$stage" 2>/dev/null; then
        echo "[nakon] run_as='$5': no such account, or chown failed" >&2
        rm -rf "$stage"
        return 127
    fi
    timeout -k 30 "$STEP_TIMEOUT" runuser -u "$5" -- "$4" -c \\
        'cd "$1" || exit 127; if [ -f ./vars.env ]; then set -a; . ./vars.env; set +a; fi; exec "$2" ./step' \\
        _ "$stage" "$4"
    rc=$?
    rm -rf "$stage"
    return $rc
}}

# Wait out boot-time apt/dpkg locks.
nakon_dpkg_wait() {{
    for _ in $(seq 1 90); do
        if command -v fuser >/dev/null 2>&1; then
            fuser /var/lib/dpkg/lock-frontend /var/lib/dpkg/lock \\
                  /var/lib/apt/lists/lock /var/cache/apt/archives/lock \\
                  >/dev/null 2>&1 || return 0
        elif command -v lsof >/dev/null 2>&1; then
            lsof /var/lib/dpkg/lock-frontend /var/lib/dpkg/lock \\
                 /var/lib/apt/lists/lock /var/cache/apt/archives/lock \\
                 >/dev/null 2>&1 || return 0
        else
            pgrep -x apt-get >/dev/null 2>&1 || pgrep -x unattended-upgrade >/dev/null 2>&1 || return 0
        fi
        sleep 2
    done
    return 1
}}

nakon_dpkg_wait

# Make apt wait for the dpkg lock instead of failing. Re-run before every step;
# removed at the end of the run.
NAKON_APT_CONF=/etc/apt/apt.conf.d/99nakon-lock-timeout
if command -v apt-get >/dev/null 2>&1; then
    echo 'DPkg::Lock::Timeout "600";' > "$NAKON_APT_CONF" 2>/dev/null || NAKON_APT_CONF=""
else
    NAKON_APT_CONF=""
fi
"""


def render_run_sh(steps: list, plan_id: str, bundle_id: str, version: str) -> str:
    parts = [_preamble(plan_id, bundle_id, len(steps), version)]

    for index, step in enumerate(steps):
        label = step_label(step)
        script = f'"$PLAN_DIR/steps/{step_basename(index, step)}"'
        workdir = f'"$PLAN_DIR/files/{index:03d}"'
        idx = f"{index:03d}"

        interp = _INTERPRETER.get(step["type"], "bash")
        run_as = step["run_as"] or "root"
        vars_file = f'"$PLAN_DIR/vars/{idx}.env"' if step["vars"] else '""'
        kind = "config"

        runner = (
            f"nakon_step_root {script} {workdir} {vars_file} {interp}"
            if run_as == "root"
            else f"nakon_step_user {script} {workdir} {vars_file} {interp} {shlex.quote(run_as)}"
        )

        parts.append(f"""
# ── step {idx} — {kind}: {label} (run_as={_WHITESPACE.sub(' ', run_as)}) {'─' * max(0, 30 - len(label))}
printf '%s %s %s %s\\n' "{MARKER_BEGIN}" "{idx}" "{kind}" {shlex.quote(label)}
_nakon_t0=$SECONDS
nakon_dpkg_wait || echo "[nakon] apt locks remained busy before step {idx}" >&2
{runner}
nakon_record {idx} {shlex.quote(label)} {kind} $? $((SECONDS - _nakon_t0))
""")

    parts.append(f"""
[ -n "$NAKON_APT_CONF" ] && rm -f "$NAKON_APT_CONF"

echo "{MARKER_DONE} failed=$FAILED steps=$TOTAL"
# Always exit 0; the Python side owns the pass/fail decision.
exit 0
""")
    return "".join(parts)
