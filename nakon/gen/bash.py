"""Generate the Linux side of a plan: run.sh, per-step scripts, and vars files.

Design note — script bodies are NEVER inlined into run.sh. Three concrete reasons, all
observed in the live catalog:

1. `splunk` contains a literal `exit 0` in its already-installed branch. Inlined (even as a
   shell function) that terminates the driver, and every later step silently vanishes.
2. `set -e` is a shell-global option, not function-scoped, and ten catalog scripts open with
   it. Inlining leaks `-e` into the driver so the first non-zero anywhere aborts the box —
   exactly the opposite of the collect-and-report behaviour deploy.py had.
3. A body containing the heredoc delimiter breaks out of the heredoc; that class of bug is
   why script upload moved to SFTP in the first place.

Subshells fix (1) and (2) but not (3). Separate files fix all three, and each step keeps its
own process, its own $?, and its own working directory.
"""

import shlex

from . import MARKER_BEGIN, MARKER_DONE, MARKER_RC, step_basename, step_label

# Wall-clock cap per step. splunk pulls a ~500 MB installer and roundcube drags in
# apache+mariadb+php, so this has to be generous; override with NAKON_STEP_TIMEOUT.
DEFAULT_STEP_TIMEOUT = 1800

_INTERPRETER = {"bash": "bash", "command": "sh"}


def render_vars(var_values: dict) -> str:
    """Shell-quoted assignments, sourced (under `set -a`) inside the step's own subshell.

    Catalog scripts read these as ordinary shell variables — "$PACKAGE", "$USERNAME" — which
    is what the old build_script() delivered by prepending the assignments to the script body.
    Keeping them in a separate file means the catalog script itself is stored byte-for-byte;
    the cost is that they have to be exported to cross into the step's process.

    Sourcing inside the subshell is what keeps one step's vars from leaking into the next —
    implicitly true before, because every configuration got its own remote process.
    """
    lines = [f"{key}={shlex.quote(str(value))}" for key, value in sorted(var_values.items())]
    return "".join(f"{line}\n" for line in lines)


def render_package_step(package: str) -> str:
    """A self-contained installer script for a raw package fallback.

    Carries the apt/dnf/yum/apk detection and the dpkg-lock wait that used to live in
    configurations.install_package(). Self-contained because it runs as its own process, so
    it cannot rely on helper functions defined in the driver.

    The package name is passed as a real argv element after `--` rather than interpolated
    into a command string, so an odd or hostile name cannot inject.
    """
    return f"""#!/bin/bash
# GENERATED BY nakon — package fallback: {package}
# A depends_on entry that matched no configuration name, installed via the host's package
# manager. Mirrors the old configurations.install_package().

PKG={shlex.quote(package)}

# Boot-time unattended-upgrades can hold the apt locks for ~2 min on a freshly-booted box.
# All four are checked, not just dpkg's lock-frontend: `apt-get update` takes
# /var/lib/apt/lists/lock and nothing else, so waiting on lock-frontend alone still races
# and fails with "Could not get lock /var/lib/apt/lists/lock".
nakon_dpkg_wait() {{
    command -v fuser >/dev/null 2>&1 || return 0
    for _ in $(seq 1 90); do
        fuser /var/lib/dpkg/lock-frontend /var/lib/dpkg/lock \\
              /var/lib/apt/lists/lock /var/cache/apt/archives/lock \\
              >/dev/null 2>&1 || break
        sleep 2
    done
}}

if command -v apt-get >/dev/null 2>&1; then
    nakon_dpkg_wait
    # -o DPkg::Lock::Timeout makes apt itself block for the lock instead of failing. The
    # fuser poll above is inherently racy — unattended-upgrades can reclaim the lock between
    # the check and the install — and this closes that window. apt 2.0+ (Ubuntu 20.04+).
    DEBIAN_FRONTEND=noninteractive apt-get -o DPkg::Lock::Timeout=600 install -y -- "$PKG"
elif command -v dnf >/dev/null 2>&1; then
    dnf install -y -- "$PKG"
elif command -v yum >/dev/null 2>&1; then
    yum install -y -- "$PKG"
elif command -v apk >/dev/null 2>&1; then
    apk add --no-cache -- "$PKG"
else
    echo "[nakon] no supported package manager found for '$PKG'" >&2
    exit 1
fi
"""


def _preamble(plan_id: str, bundle_id: str, total: int, version: str) -> str:
    return f"""#!/usr/bin/env bash
# GENERATED BY nakon {version} — do not edit.
#   bundle {bundle_id}
#   plan   {plan_id}
#   {total} step(s), platform=linux
#
# Deliberately no `set -e`: one failing configuration must not abort the rest of the box.
# Every step runs as its own process and its exit code is recorded, never acted on.

# Drop whatever is left on stdin before running anything. deploy feeds a password line for
# `sudo -S`, but under a NOPASSWD sudoers rule sudo never consumes it — and it would then be
# inherited by the first child that reads stdin.
exec </dev/null

PLAN_DIR="$(cd -- "$(dirname -- "${{BASH_SOURCE[0]}}")" && pwd)"
REPORT="$PLAN_DIR/report.tsv"
TOTAL={total}
STEP_TIMEOUT="${{NAKON_STEP_TIMEOUT:-{DEFAULT_STEP_TIMEOUT}}}"
FAILED=0
: > "$REPORT"

nakon_record() {{  # idx name kind rc secs
    printf '%s\\t%s\\t%s\\t%s\\t%s\\n' "$1" "$2" "$3" "$4" "$5" >> "$REPORT"
    # Tab-delimited, matching report.tsv and powershell.py's Nakon-Record, on purpose: a
    # plain-space-delimited line can't tell an empty field from a separator, so an unexpected
    # blank here would silently shift $5 into the rc column on the Python side instead of
    # being visibly wrong.
    printf '%s %s\\t%s\\t%s\\n' "{MARKER_RC}" "$1" "$4" "$5"
    [ "$4" -eq 0 ] || FAILED=$((FAILED + 1))
}}

# Run one step as root. The whole driver already runs under a single sudo, so this is just a
# subshell: its own CWD (for the ./<attachment> contract), its own sourced vars, its own $?.
nakon_step_root() {{  # script workdir varsfile interp
    (
        cd -- "$2" || exit 127
        # `set -a` so the assignments are exported. The step script is a separate process
        # (it keeps its own `set -e` and `exit` to itself), and a plain shell variable would
        # not survive into it. The old deploy.py got the same effect by prepending the
        # assignments to the script body; keeping them in their own file leaves the catalog
        # script on disk byte-for-byte identical to what's in vulndb.
        if [ -n "$3" ]; then set -a; . "$3"; set +a; fi
        exec timeout -k 30 "$STEP_TIMEOUT" "$4" "$1"
    )
}}

# Run one step as a non-root account named by the configuration's run_as. The plan directory
# lives under /root and is unreadable to that account, so stage a private copy it can read.
# (The old deploy.py compared run_as to "root" and otherwise ran as the SSH user, so a
# run_as of e.g. www-data silently ran as ubuntu. This actually honours it.)
nakon_step_user() {{  # script workdir varsfile interp user
    local stage rc
    stage="$(mktemp -d /tmp/nakon-runas.XXXXXXXX)" || return 127
    chmod 0700 "$stage" || {{ rm -rf "$stage"; return 127; }}
    if [ -n "$2" ] && [ -d "$2" ]; then cp -a "$2/." "$stage/" 2>/dev/null || true; fi
    cp -a "$1" "$stage/step" || {{ rm -rf "$stage"; return 127; }}
    if [ -n "$3" ]; then cp -a "$3" "$stage/vars.env" || true; fi
    if ! chown -R "$5" "$stage" 2>/dev/null; then
        echo "[nakon] run_as='$5': no such account, or chown failed" >&2
        rm -rf "$stage"
        return 127
    fi
    timeout -k 30 "$STEP_TIMEOUT" runuser -u "$5" -- "$4" -c \\
        'cd "$1" || exit 127; if [ -f ./vars.env ]; then set -a; . ./vars.env; set +a; fi; exec "$2" ./step' \\
        _ "$stage" "$4"
    rc=$?
    rm -rf "$stage"
    return $rc
}}

# Wait out any boot-time apt/dpkg lock. All four locks, not just dpkg's lock-frontend:
# `apt-get update` takes /var/lib/apt/lists/lock and nothing else, so waiting on
# lock-frontend alone still loses the race and dies with "Could not get lock
# /var/lib/apt/lists/lock" — observed on a freshly-cloned Ubuntu 24.04 box.
nakon_dpkg_wait() {{
    command -v fuser >/dev/null 2>&1 || return 0
    for _ in $(seq 1 90); do
        fuser /var/lib/dpkg/lock-frontend /var/lib/dpkg/lock \\
              /var/lib/apt/lists/lock /var/cache/apt/archives/lock \\
              >/dev/null 2>&1 || break
        sleep 2
    done
}}

# Once up front, before the first step touches a package manager. Mirrors the
# wait_for_dpkg_lock() deploy.py used to run over its own SSH channel.
nakon_dpkg_wait

# Make apt block for the dpkg lock rather than fail, for every apt invocation in this run —
# including the `apt-get install` calls inside catalog scripts, which nakon doesn't generate
# and can't rewrite. Polling with fuser above is unavoidably racy (unattended-upgrades can
# reclaim the lock between the check and the install); this is apt's own supported wait, and
# it applies run-wide because apt.conf.d fragments are additive.
#
# Scope, precisely: DPkg::Lock::Timeout covers the dpkg frontend and archives locks, i.e.
# `apt-get install`. It does NOT cover /var/lib/apt/lists/lock, which `apt-get update` takes
# and which has no wait option at all — that one is only handled by nakon_dpkg_wait above.
# No configuration in the catalog runs `apt-get update`, so that gap is currently unreachable;
# if one ever does, it needs its own lock wait.
#
# Removed at the end of the run.
NAKON_APT_CONF=/etc/apt/apt.conf.d/99nakon-lock-timeout
if command -v apt-get >/dev/null 2>&1; then
    echo 'DPkg::Lock::Timeout "600";' > "$NAKON_APT_CONF" 2>/dev/null || NAKON_APT_CONF=""
else
    NAKON_APT_CONF=""
fi
"""


def render_run_sh(steps: list, plan_id: str, bundle_id: str, version: str) -> str:
    """Emit the whole run.sh for a linux plan."""
    parts = [_preamble(plan_id, bundle_id, len(steps), version)]

    for index, step in enumerate(steps):
        label = step_label(step)
        script = f'"$PLAN_DIR/steps/{step_basename(index, step)}"'
        workdir = f'"$PLAN_DIR/files/{index:03d}"'
        idx = f"{index:03d}"

        if step["kind"] == "package":
            interp, run_as, vars_file = "bash", "root", '""'
            kind = "package"
        else:
            interp = _INTERPRETER.get(step["type"], "bash")
            run_as = step["run_as"] or "root"
            vars_file = f'"$PLAN_DIR/vars/{idx}.env"' if step["vars"] else '""'
            kind = "config"

        runner = (
            f"nakon_step_root {script} {workdir} {vars_file} {interp}"
            if run_as == "root"
            else f"nakon_step_user {script} {workdir} {vars_file} {interp} {shlex.quote(run_as)}"
        )

        parts.append(f"""
# ── step {idx} — {kind}: {label} (run_as={run_as}) {'─' * max(0, 30 - len(label))}
printf '%s %s %s %s\\n' "{MARKER_BEGIN}" "{idx}" "{kind}" {shlex.quote(label)}
_nakon_t0=$SECONDS
{runner}
nakon_record {idx} {shlex.quote(label)} {kind} $? $((SECONDS - _nakon_t0))
""")

    parts.append(f"""
# Leave the box as we found it — the apt lock-timeout fragment was ours, for this run only.
[ -n "$NAKON_APT_CONF" ] && rm -f "$NAKON_APT_CONF"

echo "{MARKER_DONE} failed=$FAILED steps=$TOTAL"
# Always exit 0. Per-step results live in report.tsv and the ##nakon markers; the Python
# side decides what counts as a failed deploy (and whether NAKON_STRICT/--strict applies).
exit 0
""")
    return "".join(parts)
